# 严格的「未来时」标记：只有这些词出现才算预告，避免把「研究/部署/召开」这类
# 已发生新闻里的常态词误判成即将发生。逐事件的 forecast_hint 用于兜底，但不含歧义词。
FUTURE_MARKERS = ('将于', '即将', '拟于', '预计将', '预期将', '前瞻', '临近',
                  '下周将', '计划于', '有望', '料将', '市场预期', '将召开', '将研究')


def _has_any(text, words):
    return any(w in text for w in words if w)


def _snippet(text, kw, width=46):
    i = text.find(kw)
    if i < 0:
        return text[:width]
    return text[max(0, i - 12):i + width]


def detect_alerts(items, no_forecast=False):
    """扫描新闻/深料条目，返回命中的重大事件预警列表。

    items: [{'t':标题,'sum':摘要,'time'|'date':时间,'src'|'query':来源}, ...]
    no_forecast: True 时只报「已发生」，不报预告类（收盘档可用）。
    """
    alerts = []
    for ev in EVENT_LIBRARY:
        happened, upcoming = [], []
        for x in items or []:
            title = str(x.get('t') or x.get('title') or '')
            body = str(x.get('sum') or x.get('content') or '')
            text = title + ' ' + body
            if not text.strip():
                continue
            meta = {
                'title': title[:90],
                'time': str(x.get('time') or x.get('date') or ''),
                'src': str(x.get('src') or x.get('query') or x.get('m') or ''),
                'hit': _snippet(text, next((k for k in ev['trigger'] if k in text), title[:8]))
            }
            # 即将发生优先：主题词 + 严格未来时标记（如「国常会将于下周召开」）
            # 只认 FUTURE_MARKERS——逐事件 forecast_hint 含「研究/部署」等已发生常态词，会误判。
            is_future = _has_any(text, FUTURE_MARKERS)
            if not no_forecast and _has_any(text, ev['forecast']) and is_future:
                upcoming.append(meta)
            # 已发生：命中主题词 + 至少一个限定词（避免泛泛提到国常会就算暴涨预警）
            elif _has_any(text, ev['trigger']) and _has_any(text, ev['must']):
                happened.append(meta)
        if not happened and not upcoming:
            continue
        stage = 'happened' if happened else 'upcoming'
        evidence = happened or upcoming
        alerts.append({
            'id': ev['id'], 'name': ev['name'], 'level': ev['level'], 'dir': ev['dir'],
            'stage': stage, 'stageLabel': '已发生' if stage == 'happened' else '即将发生',
            'evidenceCount': len(evidence),
            'evidence': evidence[:3],
            'cases': ev['cases'], 'sector': ev['sector'],
            'action': ev['action'], 'why': ev['why']
        })
    rank = {'强': 0, '中': 1, '观察': 2}
    alerts.sort(key=lambda a: (rank.get(a['level'], 9), 0 if a['stage'] == 'happened' else 1,
                               -a['evidenceCount']))
    return alerts


