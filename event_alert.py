def banner(alerts):
    """给 content.eventAlert 用的确定性提示串（模型不可用时也有强预警）。"""
    if not alerts:
        return ''
    out = []
    for a in alerts[:3]:
        out.append('⚠强预警｜%s（%s）｜%s｜%s' % (
            a['name'], a['stageLabel'], a['sector'], a['action']))
    return ' '.join(out)


def self_test():
    assert len(EVENT_LIBRARY) >= 8, '事件库覆盖不足'
    ids = {e['id'] for e in EVENT_LIBRARY}
    for need in ('gov_council_capital_market', 'stamp_duty', 'national_team_etf',
                 'external_shock', 'fed_monetary'):
        assert need in ids, '缺关键事件类型: ' + need
    # 今日国常会案例必须命中「已发生·强·up」
    a = detect_alerts([{'t': '国常会研究持续深化资本市场投融资综合改革',
                        'sum': '完善资本市场稳市机制，优化中央汇金公司类平准基金功能，提供充足流动性保障',
                        'time': '11:30', 'src': '新华社'}])
    g = [x for x in a if x['id'] == 'gov_council_capital_market']
    assert g and g[0]['level'] == '强' and g[0]['dir'] == 'up' and g[0]['stage'] == 'happened', '国常会命中失败'
    # 预告类必须标「即将发生」
    f = detect_alerts([{'t': '国务院常务会议将于下周召开，研究资本市场改革'}])
    gf = [x for x in f if x['id'] == 'gov_council_capital_market']
    assert gf and gf[0]['stage'] == 'upcoming', '预告类识别失败'
    # 印花税上调应判为 down 混合，且区分方向由 must/action 给出
    s = detect_alerts([{'t': '证券交易印花税上调至3‰', 'sum': '两市跌停859家'}])
    assert any(x['id'] == 'stamp_duty' for x in s), '印花税命中失败'
    # 无关新闻不误报
    assert detect_alerts([{'t': '某上市公司发布三季报', 'sum': '业绩符合预期'}]) == [], '误报'
    assert '国常会' in primer() and '印花税' in primer(), '注意事项未接入事件规律'
    assert '强预警' in banner(a), '强预警横幅缺失'
    return True


